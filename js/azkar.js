function extractAzkarItems(result) {


  
    if (
        Array.isArray(result)
    ) {

        return result;

    }

 
    if (
        result &&
        result.data
    ) {


         
        if (
            Array.isArray(
                result.data
            )
        ) {

            return result.data;

        }


        
        if (
            Array.isArray(
                result.data.content
            )
        ) {

            return result.data.content;

        }


       
        if (
            Array.isArray(
                result.data.azkar
            )
        ) {

            return result.data.azkar;

        }


        
        if (
            Array.isArray(
                result.data.items
            )
        ) {

            return result.data.items;

        }


      
        if (
            Array.isArray(
                result.data.data
            )
        ) {

            return result.data.data;

        }


       
        for (
            const key of Object.keys(
                result.data
            )
        ) {

            if (
                Array.isArray(
                    result.data[key]
                )
            ) {

                const possibleItems =
                    result.data[key];


                const isAzkarArray =
                    possibleItems.some(
                        item =>
                            item &&
                            typeof item === "object" &&
                            (
                                item.zekr ||
                                item.text ||
                                item.content ||
                                item.arabic ||
                                item.dua
                            )
                    );


                if (
                    isAzkarArray
                ) {

                    return possibleItems;

                }

            }

        }

    }


   
    if (
        result &&
        typeof result === "object"
    ) {

        for (
            const key of Object.keys(
                result
            )
        ) {

            if (
                Array.isArray(
                    result[key]
                )
            ) {

                const possibleItems =
                    result[key];


                const isAzkarArray =
                    possibleItems.some(
                        item =>
                            item &&
                            typeof item === "object" &&
                            (
                                item.zekr ||
                                item.text ||
                                item.content ||
                                item.arabic ||
                                item.dua
                            )
                    );


                if (
                    isAzkarArray
                ) {

                    return possibleItems;

                }

            }

        }

    }


    return [];

}

 
