async function openCategory(
    category,
    title
) {

    try {

      
        const apiKey =
            typeof category === "string"

                ? category

                : category?.apiKey ||
                  category?.slug ||
                  category?.key ||
                  "";


        if (!apiKey) {

            throw new Error(
                "API key not found"
            );

        }


        console.log(
            "Opening API category:",
            apiKey
        );

 
        const response =
            await fetch(
                `${API_URL}/${encodeURIComponent(apiKey)}`
            );


        if (!response.ok) {

            throw new Error(
                `HTTP Error: ${response.status}`
            );

        }


        
        const result =
            await response.json();


        console.log(
            "Category API Response:",
            result
        );


        
        const items =
            extractAzkarItems(
                result
            );


        console.log(
            "Extracted Azkar:",
            items
        );


       
        if (
            !Array.isArray(items) ||
            items.length === 0
        ) {

            throw new Error(
                "No azkar found"
            );

        }


       
        renderAzkar(
            items,
            title
        );


       
        const modalElement =
            document.getElementById(
                "azkarModal"
            );


        if (!modalElement) {

            throw new Error(
                "azkarModal not found"
            );

        }


        const modal =
            bootstrap.Modal.getOrCreateInstance(
                modalElement
            );


        modal.show();


    } catch (error) {

        console.error(
            "Error loading category:",
            error
        );


        showUnavailable(
            title
        );

    }

}


 
function renderAzkar(
    items,
    title
) {

    modalTitle.textContent =
        title;


    azkarContainer.innerHTML =
        "";


  
    if (
        !Array.isArray(items) ||
        items.length === 0
    ) {

        showUnavailable(
            title
        );

        return;

    }


   
    const validAzkar =
        items.filter(
            item => {


                if (
                    !item ||
                    typeof item !== "object"
                ) {

                    return false;

                }


                const text =
                    item.zekr ??
                    item.text ??
                    item.content ??
                    item.arabic ??
                    item.dua ??
                    item.title ??
                    "";


                return String(
                    text
                ).trim() !== "";

            }
        );


    
    if (
        validAzkar.length === 0
    ) {

        showUnavailable(
            title
        );

        return;

    }


  
    validAzkar.forEach(
        (
            item,
            index
        ) => {

 
            const text =
                item.zekr ??
                item.text ??
                item.content ??
                item.arabic ??
                item.dua ??
                item.title ??
                "";

 
            const repeat =
                item.repeat ??
                item.count ??
                item.repetition ??
                item.times ??
                "";

 
            const source =
                item.source ??
                item.reference ??
                item.ref ??
                "";


 
            const bless =
                item.bless ??
                item.benefit ??
                item.description ??
                item.fadl ??
                "";


         
            const zekrElement =
                document.createElement(
                    "div"
                );


            zekrElement.className =
                "zekr-item";

 
            zekrElement.innerHTML = `

                <div class="zekr-number">

                    ${index + 1}

                </div>


                <div class="zekr-content">


                    <div class="zekr-text">

                        ${text}

                    </div>


                    ${
                        bless
                            ? `
                            <div class="zekr-bless">

                                <i class="fas fa-star"></i>

                                ${bless}

                            </div>
                            `
                            : ""
                    }


                    <div class="zekr-footer">


                        ${
                            source
                                ? `
                                <div class="zekr-source">

                                    <i class="fas fa-book-open"></i>

                                    ${source}

                                </div>
                                `
                                : ""
                        }


                        ${
                            repeat
                                ? `
                                <div class="zekr-count">

                                    <i class="fas fa-redo"></i>

                                    ${repeat} مرة

                                </div>
                                `
                                : ""
                        }


                    </div>


                </div>

            `;


            azkarContainer.appendChild(
                zekrElement
            );

        }
    );

}


 
